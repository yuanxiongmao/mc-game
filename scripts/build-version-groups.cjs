const fs=require('node:fs'),path=require('node:path');
const {blocks,versionDates}=require('../data.js');
const manifest=require('../sources/manifest.json');
const parents=require('../sources/version-parents.json');
const releases=manifest.versions.filter(v=>v.type==='release').map(v=>({id:v.id,time:Date.parse(v.releaseTime)})).sort((a,b)=>a.time-b.time);
function classify(v){
 if(/^(rd-|Classic|Indev|Infdev)/.test(v))return 'pre-alpha';
 if(/^Alpha/.test(v))return 'alpha';
 if(/^Beta/.test(v))return /^Beta 1\.9 Prerelease/.test(v)?'1.0':'beta';
 const direct=v.match(/^(\d+\.\d+)/);if(direct)return direct[1];
 if(parents[v])return parents[v].split('.').slice(0,2).join('.');
 const date=versionDates[v];if(!Number.isFinite(date))throw Error('Missing date: '+v);
 const first=new Map();for(const r of releases){const major=r.id.split('.').slice(0,2).join('.');if(!first.has(major))first.set(major,r);}
 const release=[...first.values()].find(r=>r.time>=date);if(!release)throw Error('Missing release: '+v);
 return release.id==='1.0'?'1.0':release.id.split('.').slice(0,2).join('.');
}
const groups=Object.fromEntries([...new Set(blocks.map(b=>b.version))].map(v=>[v,classify(v)]));
fs.writeFileSync(path.resolve(__dirname,'../version-groups.js'),`/* Generated by scripts/build-version-groups.cjs from saved release dates. */\n(function(root){const groups=${JSON.stringify(groups,null,2)};if(typeof module!=='undefined')module.exports=groups;else root.BlockVersionGroups=groups;})(globalThis);\n`);
console.log('Version categories:',[...new Set(Object.values(groups))].join(', '));
